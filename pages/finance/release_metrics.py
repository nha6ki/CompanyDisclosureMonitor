"""Read consolidated, single-quarter figures from SEC earnings-release exhibits.

Amounts are in USD millions. A cash-flow table covering only YTD is never used.
The selected table row and reported quarter are returned with each amount.
"""
from datetime import date, datetime
from html.parser import HTMLParser
import re


class Exhibit(HTMLParser):
    """Collect top-level table grids, outside headings and slide transcripts."""
    def __init__(self):
        super().__init__()
        self.tables = []
        self.slides = []
        self.outside = []
        self.depth = 0
        self.cell = self.row = None

    def handle_starttag(self, tag, attrs):
        if tag == 'table':
            if not self.depth:
                self.tables.append((' '.join(' '.join(self.outside).split())[-450:], []))
                self.outside.clear()
            self.depth += 1
        if self.depth != 1:
            return
        if tag == 'tr':
            self.row = []
            self.tables[-1][1].append(self.row)
            self.pos = 0
        elif tag in ('td', 'th') and self.row is not None:
            attrs = dict(attrs)
            self.span = int(attrs.get('colspan', 1))
            self.cell = []

    def handle_data(self, text):
        if text.lstrip().startswith('In millions of USD'):
            self.slides.append(' '.join(text.split()))
        if not self.depth:
            self.outside.append(text)
        elif self.cell is not None:
            self.cell.append(text)

    def handle_endtag(self, tag):
        if self.depth == 1 and tag in ('td','th') and self.cell is not None:
            value = ' '.join(''.join(self.cell).split())
            if value:
                self.row.append((self.pos, self.pos+self.span, value))
            self.pos += self.span
            self.cell = None
        if tag == 'tr' and self.depth == 1:
            self.row = None
        if tag == 'table':
            self.depth = max(0, self.depth-1)


REVENUE = {'AAPL':'Total net sales', 'AMZN':'Total net sales', 'GOOGL':'Revenues',
           'META':'Revenue', 'MSFT':'Total revenue', 'NVDA':'Revenue'}
OPERATING = ('Operating income', 'Income from operations')
CASH = ('Net cash provided by operating activities', 'Net cash provided by (used in) operating activities',
        'Net cash from operations', 'Cash generated by operating activities')
CAPEX = ('Purchases of property and equipment', 'Payments for acquisition of property, plant and equipment',
         'Purchase related to property and equipment and intangible assets',
         'Purchases related to property and equipment and intangible assets', 'Additions to property and equipment')
NUMBER = re.compile(r'(?:\d{1,3}(?:,\d{3})+|\d+)(?:\.\d+)?')


def number(text):
    text = text.replace('$', '').replace(' ', '')
    neg = text.startswith('(') and text.endswith(')')
    value = text[1:-1] if neg else text
    if not NUMBER.fullmatch(value):
        return None
    value = value.replace(',', '')
    amount = float(value) if '.' in value else int(value)
    return -amount if neg else amount


def quarter_columns(rows, end):
    """Resolve dates using only the header covering three-month columns."""
    groups = [(i,c) for i,r in enumerate(rows[:8]) for c in r
              if re.match(r'^(?:three months|quarter) ended',c[2],re.I)]
    if len(groups) != 1:
        return {}
    idx, (lo,hi,title) = groups[0]
    following = rows[idx+1:idx+3]
    if not following:
        return {}
    year_row = next((r for r in following if any(re.fullmatch(r'(?:[a-z]+\s+\d+,\s*)?20\d\d',v,re.I)
                                                  for _,_,v in r)), [])
    # An isolated single-quarter group sometimes sits offset above its two year columns.
    standalone = (len(rows[idx]) == 1 and len(year_row) == 2)
    shared_day = re.sub(r'^(?:three months|quarter) ended\s*', '', title, flags=re.I)
    cols = {}
    for left,right,val in year_row:
        if not standalone and not lo <= left < right <= hi:
            continue
        if re.fullmatch(r'20\d\d',val):
            day = shared_day or next((v for l,h,v in following[0] if l <= left < right <= h), '')
            val = day.rstrip(',') + ', ' + val
        try:
            col_end = datetime.strptime(re.sub(r',\s*', ', ', val), '%B %d, %Y').date()
        except ValueError:
            continue
        if col_end in cols:
            return {}
        cols[col_end] = (left,right)
    previous = [dt for dt in cols if 357 <= (end-dt).days <= 371]
    if end not in cols or len(previous) != 1:
        return {}
    return {'current':(end,cols[end]), 'prior':(previous[0],cols[previous[0]])}


def select_row(rows, columns, period, labels):
    end,(lo,hi) = columns[period]
    found = []
    for row in rows:
        label = row[0][2]
        clean = re.sub(r' \((?:Note )?\d+\)$','',label,flags=re.I)
        if clean not in labels:
            continue
        n = number(''.join(text for left,right,text in row if lo<=left<right<=hi))
        if n is not None:
            found.append((n,label))
    if found and len(set(n for n,label in found)) == 1:
        return dict(value=found[0][0],row=found[0][1],column='Quarter ended '+end.isoformat())


def tables_data(doc,symbol,end):
    results = {}
    for context,table in doc.tables:
        rows = [r for r in table if r]
        # Some exhibits put company, statement and units inside the table.
        head = context + ' ' + ' '.join(r[0][2] for r in rows[:4] if len(r)==1)
        income = re.search(r'(?:consolidated statements of (?:income|operations)|microsoft corporation income statements)\s*\((?:unaudited\)\s*\()?in millions',head,re.I)
        cash = re.search(r'(?:consolidated statements of cash flows|cash flows statements)\s*\((?:unaudited\)\s*\()?in millions',head,re.I)
        if not income and not cash:
            continue
        columns = quarter_columns(rows,end)
        if not columns:
            continue
        metrics = [('operating','current',OPERATING),('revenue','current',[REVENUE[symbol]]),
                   ('priorRevenue','prior',[REVENUE[symbol]])] if income else [
                   ('cash','current',CASH),('capex','current',CAPEX)]
        for key,period,labels in metrics:
            point = select_row(rows,columns,period,labels)
            if point is not None:
                results.setdefault(key,[]).append(point)
    return {key:values[0] for key,values in results.items() if len(values)==1}


def tesla_data(doc,record):
    results = {}
    end = date.fromisoformat(record['end'])
    if end.strftime('%m-%d') not in ('03-31','06-30','09-30','12-31'):
        return {}
    q = (end.month+2)//3
    for slide in doc.slides:
        title = re.sub(r'\s','',slide).upper()
        if re.search(r'STATEMENTOFOPERATIONS\(UNAUDITED\)\d+',title):
            separator = ' REVENUES '
            labels = [('revenue','Total revenues',end.year),('priorRevenue','Total revenues',end.year-1),
                      ('operating','Income from operations',end.year)]
        elif re.search(r'STATEMENTOFCASHFLOWS\(UNAUDITED\)\d+',title):
            separator = ' CASH FLOWS FROM OPERATING ACTIVITIES '
            labels = [('cash','Net cash provided by operating activities',end.year),
                      ('capex','Capital expenditures',end.year)]
        else:
            continue
        header,sep,body = slide.partition(separator)
        if not sep:
            continue
        headers = re.findall(r'\bQ[1-4]-20\d\d\b',header)
        if len(headers) != len(set(headers)):
            continue
        for key,label,year in labels:
            col = f'Q{q}-{year}'
            if col not in headers:
                continue
            match = re.findall(r'\b'+label+r' ([-\d(),. —]+)(?=[A-Za-z])',body,re.I)
            if len(match)!=1:
                continue
            amounts = match[0].split()
            # Some slides put a parenthesized footnote before the five amounts.
            if len(amounts)==len(headers)+1 and re.fullmatch(r'\(\d\)',amounts[0]):
                amounts = amounts[1:]
            if len(amounts)!=len(headers):
                continue
            value = number(amounts[headers.index(col)])
            if value is not None:
                results.setdefault(key,[]).append(dict(value=value,row=label,column=col))
    return {key:values[0] for key,values in results.items() if len(values)==1}


def read_release(symbol, record, html_bytes):
    doc = Exhibit()
    doc.feed(html_bytes.decode('utf-8-sig'))
    doc.close()
    points = tesla_data(doc,record) if symbol=='TSLA' else tables_data(doc,symbol,date.fromisoformat(record['end']))
    if 'capex' in points:
        # Source cash-flow statements record purchases as a negative cash flow.
        points['capex']['value'] = -points['capex']['value']
        if symbol=='NVDA':
            points['capex']['scope'] = 'includesIntangibles'
        if symbol=='TSLA' and record['period']>='FY2025Q1':
            points['capex']['scope'] = 'includesEnergySystems'
    return points
